// 첫 글자로 찾아보기 위한 색인
const WORD_BY_FIRST = WORD_CHAIN.reduce((map, word) => {
  const first = word[0];
  (map[first] = map[first] || []).push(word);
  return map;
}, {});

// 이 낱말 다음에 이어 붙일 수 있는 낱말들
function chainOptions(word, used) {
  const last = word[word.length - 1];
  return (WORD_BY_FIRST[last] || []).filter((w) => w !== word && !(used || []).includes(w));
}

// 다음 말이 또 있는(놀이가 이어지는) 낱말을 우선 고른다.
function chainPick(word, used) {
  const options = chainOptions(word, used);
  if (!options.length) return null;
  const alive = options.filter((w) => chainOptions(w, [...(used || []), w]).length > 0);
  return pick(alive.length ? alive : options);
}

// 두 번 이상 이어갈 수 있는 낱말로 시작한다.
function chainStartWord(used) {
  const candidates = WORD_CHAIN.filter((word) => {
    const next = chainOptions(word, used);
    return next.some((w) => chainOptions(w, [...(used || []), w]).length > 0);
  });
  return pick(candidates);
}
